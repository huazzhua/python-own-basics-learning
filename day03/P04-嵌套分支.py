# 嵌套分支

# 案例：三位状态码，左边第一位标识大小写状态(1-表示大学，0-表示小写)，第二位标识输入法语言（1-简体中文，0-英语键盘），第三位标识输入法模式（1-中文，0-英文），判断输入法状态

state = 0b000

# 判断是否为大小写状态（判断第一位是1）
if state & 0b100 == 0b100:
    print("此时为大写状态")
else:
    # 判断是简体中文还是还是英语(判断第二位是1)
    if state & 0b010 == 0b010:
        # 判断是英文还是中文(判断第三位是1)
        if state & 0b001 == 0b001:
            print("简体中文-中文模式")
        else:
            print("简体中文-英文模式")
    else:
        print("英语")